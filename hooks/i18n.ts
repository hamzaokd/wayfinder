export type Lang = 'en' | 'fr'

/** The strings in use. Every module reads it at call time, so a language change applies on the next draw. */
export let T: typeof EN = EN

/** French for a `language` setting that names it ("french", "français", "fr", "fr-FR"); English for anything else or nothing. */
export function langOf(setting: unknown): Lang {
  return typeof setting === 'string' && /^(fr\b|fr[-_]|french|fran[cç]ais)/i.test(setting.trim()) ? 'fr' : 'en'
}

export function setLang(lang: Lang): void {
  T = lang === 'fr' ? FR : EN
}
